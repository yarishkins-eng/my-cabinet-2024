/**
 * 🔴 Этап В-1. Разбор метки, с которой Телеграм запускает мини-приложение.
 *
 * Зачем это существует. Человек уходит платить во ВНЕШНИЙ браузер, и кнопка провайдера
 * «Вернуться в магазин» — единственное, что он там видит. Раньше она вела на адрес сайта
 * кабинета, где человек не авторизован, и он упирался в форму входа (поймано живым проходом
 * владельца 23.08.2026). Теперь она ведёт в Телеграм ссылкой `t.me/<бот>?startapp=<метка>`,
 * Телеграм запускает мини-приложение, и метка приезжает сюда.
 *
 * Метка нарочно КОРОТКАЯ и с жёсткой грамматикой, а не адресом внутри: Телеграм разрешает в
 * `startapp` только `A-Za-z0-9_-`, и всё, что приезжает снаружи, разбирается как чужое.
 * Адрес возврата на кассу через метку НЕ передаётся — он лежит в памяти браузера
 * (`topUpStorage`), потому что это тот же браузер того же человека, а не чужой ввод.
 */

/** `tup-<способ>-<ok|fail>` — возврат с пополнения. Способ ограничен именами, которые
 *  выдаёт сервер (`telegram_stars`, `kassa_ai`, `platega`, …): строчные, цифры, подчёркивание. */
const TOP_UP_START_PARAM_RE = /^tup-([a-z0-9_]{1,32})-(ok|fail)$/;

/**
 * Превратить метку запуска во внутренний адрес мини-приложения.
 *
 * Возвращает `null` на любой незнакомой метке — это не ошибка: метки заводят и другие
 * механизмы, и чужую нам трогать нельзя.
 *
 * Собранный адрес НАМЕРЕННО совпадает с тем, что сервер строил раньше
 * (`/balance/top-up/result?method=…&status=…`): экран результата умеет его читать с этапа Б-1,
 * и новой ветки поведения здесь не появляется — меняется только дверь, через которую пришли.
 */
export function resolveStartParamPath(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const match = TOP_UP_START_PARAM_RE.exec(raw);
  if (!match) return null;
  const params = new URLSearchParams({
    method: match[1],
    status: match[2] === 'ok' ? 'success' : 'failed',
  });
  return `/balance/top-up/result?${params}`;
}
