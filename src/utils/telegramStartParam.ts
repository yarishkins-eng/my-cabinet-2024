/**
 * 🔴 Этап В-1. Разбор метки, с которой Телеграм запускает мини-приложение.
 *
 * Зачем это существует. Человек уходит платить во ВНЕШНИЙ браузер, и кнопка провайдера
 * «Вернуться в магазин» — единственное, что он там видит. Раньше она вела на адрес сайта
 * кабинета, где человек не авторизован, и он упирался в форму входа (поймано живым проходом
 * владельца 23.08.2026). Теперь она ведёт в Телеграм ссылкой `t.me/<бот>?startapp=<метка>`.
 * Метка приезжает сюда, КОГДА Телеграм поднимает мини-приложение заново; если прежний документ
 * уцелел, человека возвращает на его же экран машинерия этапа К-1 — подробнее в
 * `TelegramStartParamRouter`.
 *
 * Меток две — с пополнения баланса и с прямой оплаты картой. Обе нарочно КОРОТКИЕ и с
 * жёсткой грамматикой, а не с адресом внутри: Телеграм разрешает в `startapp` только
 * `A-Za-z0-9_-`, и всё, что приезжает снаружи, разбирается как чужое.
 * Адрес возврата на кассу через метку НЕ передаётся — он лежит в памяти браузера
 * (`topUpStorage`), потому что это тот же браузер того же человека, а не чужой ввод.
 */

/** `tup-<способ>-<ok|fail>` — возврат с ПОПОЛНЕНИЯ баланса. Способ ограничен именами, которые
 *  выдаёт сервер (`telegram_stars`, `kassa_ai`, `platega`, …): строчные, цифры, подчёркивание. */
const TOP_UP_START_PARAM_RE = /^tup-([a-z0-9_]{1,32})-(ok|fail)$/;

/** `co_<номер заказа>_<ok|fail>` — возврат с ПРЯМОЙ оплаты картой (полная цена заказа).
 *
 *  ⚠️ Разделитель здесь `_`, а у метки пополнения `-`, и это не небрежность. Каждый выбран
 *  так, чтобы не встречаться внутри своей же начинки: номер заказа — `uuid4`, в нём есть
 *  дефисы и нет подчёркиваний; имя способа оплаты — ровно наоборот. Один разделитель на обе
 *  метки сделал бы разбор двусмысленным. Собирает эти метки бот
 *  (`app/services/device_first_payment_service.py`) — менять только ПАРОЙ. */
const CHECKOUT_START_PARAM_RE = /^co_([A-Za-z0-9-]{1,64})_(ok|fail)$/;

/**
 * Превратить метку запуска во внутренний адрес мини-приложения.
 *
 * Возвращает `null` на любой незнакомой метке — это не ошибка: метки заводят и другие
 * механизмы, и чужую нам трогать нельзя.
 *
 * Собранный адрес НАМЕРЕННО совпадает с тем, что сервер строил раньше
 * (`/balance/top-up/result?method=…&status=…`): экран результата умеет его читать с этапа Б-1,
 * и новой ветки поведения здесь не появляется — меняется только дверь, через которую пришли.
 */
export function resolveStartParamPath(raw: string | null | undefined): string | null {
  if (!raw) return null;

  const topUp = TOP_UP_START_PARAM_RE.exec(raw);
  if (topUp) {
    const params = new URLSearchParams({
      method: topUp[1],
      status: topUp[2] === 'ok' ? 'success' : 'failed',
    });
    return `/balance/top-up/result?${params}`;
  }

  // Прямая оплата картой возвращает человека НА ЕГО ЗАКАЗ. Адрес собирается ровно тот же,
  // что сервер строил раньше для сайта (`/subscription/purchase?checkout=…[&payment=failed]`),
  // — меняется только дверь, через которую пришли, и то, что за ней человек авторизован.
  const checkout = CHECKOUT_START_PARAM_RE.exec(raw);
  if (checkout) {
    const params = new URLSearchParams({ checkout: checkout[1] });
    if (checkout[2] === 'fail') params.set('payment', 'failed');
    return `/subscription/purchase?${params}`;
  }

  return null;
}
