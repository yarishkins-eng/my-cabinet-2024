import { describe, expect, it } from 'vitest';
import { LIVE_STATE_QUERY_KEYS } from './liveStateRefresh';

/**
 * 🔴 Это ОСНОВНОЙ путь обновления для мини-приложения: возврат вкладки из фона и
 * переподключение сокета. Мини-приложение живёт в вебвью часами, `refetchOnWindowFocus`
 * выключен глобально, интервала нет — что не перечислено здесь, то не обновляется вовсе.
 *
 * Скидку клиента сюда забыли добавить вместе с баннером (этап СК-2): жест «потянуть вниз»
 * починили, а этот путь нет. Нашёл критик полноты волны 2.
 */
describe('живое обновление состояния', () => {
  it('перечитывает скидку клиента, иначе сгоревшее предложение предлагается вечно', () => {
    const keys = LIVE_STATE_QUERY_KEYS.map(([key]) => key);

    expect(keys).toContain('promo-offers');
    expect(keys).toContain('active-discount');
  });
});
