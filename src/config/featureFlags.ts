/**
 * Фиче-флаги фронта кабинета.
 *
 * Объединённый экран (редизайн «Главная + Подписка», Чат 3) собирается ПОД флагом,
 * выключенным по умолчанию. В проде живёт старый `Dashboard`; новый `DashboardUnified`
 * собирается рядом (отдельным lazy-чанком) и не виден пользователям, пока флаг OFF.
 * Включение — в конце Чата 3b, после одобрения владельцем. Откат — снять флаг.
 *
 * Vite пробрасывает на фронт только переменные с префиксом `VITE_` (см. `.env`).
 * Поле живёт в `.env` на сервере и НЕ в git — поэтому деплой 3a по умолчанию OFF.
 */

/** Объединённый экран на «/» вместо старого Dashboard. `VITE_UNIFIED_HOME=1` → ВКЛ. */
export const UNIFIED_HOME_ENABLED = import.meta.env.VITE_UNIFIED_HOME === '1';

/**
 * Dev-витрина состояний экрана (песочница на фикстурах, без авторизации/прода).
 * По умолчанию доступна ТОЛЬКО в режиме разработки (`npm run dev`) — в прод-сборке
 * `import.meta.env.DEV` ложно, и роут витрины не появляется. Можно форсировать
 * `VITE_SCREEN_SHOWCASE=1` (например, чтобы посмотреть в prod-сборке локально).
 */
export const SCREEN_SHOWCASE_ENABLED =
  import.meta.env.DEV || import.meta.env.VITE_SCREEN_SHOWCASE === '1';
